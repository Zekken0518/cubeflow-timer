import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

// Run after rebuilding CSS and after every change to a shipped file.
const files = [
  'index.html', 'CUBE Timer.html', 'assets/app.css', 'assets/offline.js',
  'assets/fonts/fonts.css',
  ...readdirSync('assets/fonts').filter(name => /\.(ttf|woff2?)$/.test(name)).map(name => `assets/fonts/${name}`),
];
const hash = createHash('sha256');
for (const file of files) hash.update(file).update(readFileSync(file));
const version = hash.digest('hex').slice(0, 16);
writeFileSync('sw.js', `// Generated by scripts/build-offline.mjs. Do not edit manually.
const CACHE_PREFIX = 'cubeflow-offline-' + self.registration.scope;
const CACHE_NAME = CACHE_PREFIX + '-${version}';
const FILES = ${JSON.stringify(files)};
const urls = FILES.map(file => new URL(file, self.registration.scope).href);
self.addEventListener('install', event => {
  // Installation is atomic: never activate an incomplete offline bundle.
  event.waitUntil(caches.open(CACHE_NAME).then(cache =>
    cache.addAll(urls.map(url => new Request(url, { cache: 'reload' })))
  ));
  // Updates wait until all existing app tabs close; never interrupt a solve.
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith(CACHE_PREFIX + '-') && key !== CACHE_NAME) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  url.search = '';
  url.hash = '';
  if (url.href === self.registration.scope) url.pathname += 'index.html';
  if (!urls.includes(url.href)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    return (await cache.match(url.href)) || fetch(event.request);
  })());
});
`);
console.log(`Offline bundle ${version}: ${files.length} files`);
